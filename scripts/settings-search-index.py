#!/usr/bin/env python3
"""Derive the search catalog from settings row declarations. --check rejects stale output."""
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'native/Sources/Orbit/Settings'
OUTPUT = SOURCE / 'BrowserSettingsSearchCatalog.swift'

def quoted(value):
    return json.dumps(value, ensure_ascii=False)

def catalog():
    entries = {}
    source = (SOURCE / 'BrowserSettingsOrbitPanes.swift').read_text()
    # Only pane bodies, never helper definitions, sheet bodies or runtime values.
    regions = list(re.finditer(r'private var (general|profiles|links|shortcuts|appearance|advanced): some View', source))
    for i, region in enumerate(regions):
        section = region[1]
        body = source[region.end():regions[i+1].start() if i+1 < len(regions) else source.index('private func profileTheme')]
        pattern = r'\b(?:settingRow|liveToggle)\(("(?:[^"\\]|\\.)*"|uiFormat\("[^"]+", applicationName\))'
        matches = list(re.finditer(pattern, body))
        for row_index, match in enumerate(matches):
            label = match[1]
            expression = 'uiText(' + label + ')' if label.startswith('"') else label.replace('applicationName', 'ProductIdentity.displayName')
            key = (section, expression)
            # A row's caption belongs to the same declaration.
            following = body[match.end():]
            caption = re.match(r',\s*(?:icon: "[^"]+",\s*)?subtitle: ("(?:[^"\\]|\\.)*")', following)
            help_expression = 'uiText(' + caption[1] + ')' if caption else '""'
            end = matches[row_index + 1].start() if row_index + 1 < len(matches) else len(body)
            row = body[match.end():end]
            # Static control labels and explanatory text are metadata; dynamic values are never read.
            words = list(dict.fromkeys(re.findall(r'uiText\(("(?:[^"\\]|\\.)*")\)', row)))
            captions = list(re.finditer(r'SettingsGroupLabel\(title: uiText\(("[^"]+")\)', body[:match.start()]))
            group = 'uiText(' + captions[-1][1] + ')' if captions else '""'
            keywords = ' + " " + '.join('uiText(' + word + ')' for word in words) if words else '""'
            entries[key] = f'.init(id: BrowserSettingsSearchEntry.rowID({expression}), section: .{section}, title: {expression}, help: {help_expression}, keywords: {keywords}, group: {group})'
    # Other controls declare metadata on their actual row, next to its accessible identifier.
    for path in sorted(SOURCE.glob('*.swift')):
        if path == OUTPUT: continue
        for match in re.finditer(r'\.settingsSearchItem\((uiText\("[^"]+"\)), section: \.(\w+), id: "([^"]+)"\)', path.read_text()):
            expression, section, identifier = match.groups()
            entries[(section, identifier)] = f'.init(id: "{identifier}", section: .{section}, title: {expression})'
    lines = '\n'.join('            ' + entry + ',' for entry in entries.values())
    return '''// Generated by scripts/settings-search-index.py from the pane definitions. Do not edit.
import BrowserCore
import BrowserShell

enum BrowserSettingsSearchCatalog {
    @MainActor static var entries: [BrowserSettingsSearchEntry] {
        [
''' + lines + '''
        ]
    }
}
'''

result = catalog()
if '--check' in sys.argv:
    if not OUTPUT.exists() or OUTPUT.read_text() != result:
        sys.exit('Settings rows changed. Run python3 scripts/settings-search-index.py')
else:
    OUTPUT.write_text(result)
