#!/usr/bin/env python3
"""Generate BrowserCore's embedded Public Suffix List from Mozilla's data file.

Usage:
  python3 -I scripts/generate-public-suffix-swift.py \
      native/ThirdParty/publicsuffix/public_suffix_list.dat \
      native/Sources/BrowserCore/Sites/BrowserPublicSuffixData.swift \
      [--tests native/ThirdParty/publicsuffix/test_psl.txt \
       native/Tests/BrowserCoreTests/BrowserPublicSuffixVectors.swift]

Rules keep both sections (ICANN and private), exceptions (!) and wildcards (*). Non-ASCII labels
are converted to their punycode A-label (`xn--`), the form URL hosts take in Orbit; the original
data file stays verbatim under ThirdParty/ with its MPL-2.0 licence.
"""
import hashlib
import re
import sys


def a_label(label: str) -> str:
    if label == "*" or label.isascii():
        return label.lower()
    return "xn--" + label.lower().encode("punycode").decode("ascii")


def ascii_rule(rule: str) -> str:
    prefix = ""
    if rule.startswith("!"):
        prefix, rule = "!", rule[1:]
    return prefix + ".".join(a_label(label) for label in rule.split("."))


def parse(data: str):
    version = commit = ""
    rules = []
    for raw in data.splitlines():
        line = raw.strip()
        if line.startswith("// VERSION:"):
            version = line.split(":", 1)[1].strip()
        elif line.startswith("// COMMIT:"):
            commit = line.split(":", 1)[1].strip()
        if not line or line.startswith("//"):
            continue
        # A rule is the first whitespace-delimited token of the line.
        rules.append(ascii_rule(line.split()[0]))
    return version, commit, rules


def swift_data(source_bytes: bytes, version: str, commit: str, rules) -> str:
    digest = hashlib.sha256(source_bytes).hexdigest()
    body = "\n".join(rules)
    assert '"""#' not in body
    return f'''// GENERATED by scripts/generate-public-suffix-swift.py — do not edit by hand.
// Rules of the Public Suffix List (https://publicsuffix.org/list/public_suffix_list.dat),
// VERSION {version}, COMMIT {commit}, SHA-256 of the data file {digest}.
// The list is maintained by Mozilla and contributors and is subject to the terms of the Mozilla
// Public License, v. 2.0: native/ThirdParty/publicsuffix/LICENSE or https://mozilla.org/MPL/2.0/.
// The verbatim data file is native/ThirdParty/publicsuffix/public_suffix_list.dat; this file only
// converts non-ASCII labels to punycode and drops comments.

extension BrowserPublicSuffixList {{
    static let embeddedVersion = "{version}"
    static let embeddedRules = #"""
{body}
"""#
}}
'''


CHECK = re.compile(r"checkPublicSuffix\((null|'[^']*'),\s*(null|'[^']*')\);")


def swift_vectors(test_text: str) -> str:
    cases = []
    # Commented-out checks (non-Internet TLDs such as .local) are not part of the suite.
    active = "\n".join(line for line in test_text.splitlines() if not line.lstrip().startswith("//"))
    for match in CHECK.finditer(active):
        domain, expected = (None if value == "null" else value[1:-1] for value in match.groups())
        if domain is None or not domain.isascii() or (expected is not None and not expected.isascii()):
            continue  # Unicode inputs: Orbit only sees punycode hosts; their xn-- forms are listed too.
        cases.append((domain, expected))
    lines = ",\n".join(
        f'        ("{d}", {"nil" if e is None else chr(34) + e + chr(34)})' for d, e in cases)
    return f'''// GENERATED by scripts/generate-public-suffix-swift.py from the Public Suffix List's official
// tests (native/ThirdParty/publicsuffix/test_psl.txt, public domain, CC0). ASCII cases only.

enum BrowserPublicSuffixVectors {{
    static let cases: [(domain: String, registrableDomain: String?)] = [
{lines}
    ]
}}
'''


def main(argv):
    if len(argv) not in (3, 6) or (len(argv) == 6 and argv[3] != "--tests"):
        print(__doc__, file=sys.stderr)
        return 2
    with open(argv[1], "rb") as handle:
        source = handle.read()
    version, commit, rules = parse(source.decode("utf-8"))
    if not rules or not version:
        print("unexpected data file", file=sys.stderr)
        return 1
    with open(argv[2], "w", encoding="utf-8") as handle:
        handle.write(swift_data(source, version, commit, rules))
    if len(argv) == 6:
        with open(argv[4], encoding="utf-8") as handle:
            vectors = swift_vectors(handle.read())
        with open(argv[5], "w", encoding="utf-8") as handle:
            handle.write(vectors)
    print(f"{len(rules)} rules, version {version}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
