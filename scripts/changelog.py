#!/usr/bin/env python3
"""Generate the static changelog from release/notes; no build dependencies or network."""
import argparse
from datetime import date
import html
from pathlib import Path
import xml.etree.ElementTree as ET

from release_notes import ROOT, SECTIONS, github_body, inline, load_all

SITE = 'https://circabrowser.com'
GENERATED = '<!-- Generated by scripts/changelog.py; edit release/notes or scripts/templates/changelog.html. -->'
ATOM = 'http://www.w3.org/2005/Atom'


def article(note, prefix='', latest=False):
    version = note.version
    day = date.fromisoformat(note.date)
    display_date = f'{day.strftime("%B")} {day.day}, {day.year}'
    parts = [f'<article class="release" id="v{version}" data-version="{version}" data-channel="{note.channel}" data-latest="{str(latest).lower()}">',
             f'  <div class="release-meta"><h2><a href="#v{version}" aria-label="Link to version {version}">{version}</a></h2>',
             f'  <time datetime="{note.date}">{display_date}</time><span class="release-channel">{note.channel.title()}</span></div>',
             '  <div class="release-copy"><h3>' + html.escape(note.title) + '</h3>',
             '  <p class="release-counts">' + html.escape(note.counts or 'Known limits') + '</p>']
    for name in SECTIONS:
        if name in note.sections:
            parts += ['  <h4>' + name + '</h4>', '  <ul>']
            parts += ['    <li>' + inline(item) + '</li>' for item in note.sections[name]]
            parts += ['  </ul>']
    if note.engine:
        parts += ['  <p class="release-engine">Engine / bundled components: ' + html.escape(note.engine) + '</p>']
    for media in note.media:
        base = prefix + 'assets/releases/' + version + '/'
        parts += ['  <figure class="release-media">',
                  f'    <video muted loop playsinline controls preload="none" poster="{base}{media.poster}" aria-label="{html.escape(media.caption, quote=True)}">',
                  f'      <source src="{base}{media.file}" type="video/mp4">',
                  f'      <a href="{base}{media.file}">Download the clip</a>',
                  '    </video><figcaption>' + html.escape(media.caption) + '</figcaption></figure>']
    parts += [f'  <a class="release-source" href="{prefix}changelog/{version}/">Release permalink ↗</a>',
              '  </div>', '</article>']
    return '\n'.join(parts)


def page(template, content, title='Changelog', canonical=SITE + '/changelog', prefix=''):
    replacements = {'CONTENT': content, 'TITLE': html.escape(title), 'CANONICAL': canonical, 'PREFIX': prefix}
    for key, value in replacements.items():
        template = template.replace('{{' + key + '}}', value)
    return template.replace('<!doctype html>', '<!doctype html>\n' + GENERATED)


def index_content(notes, latest):
    links = '\n'.join(f'<a href="#v{note.version}" data-channel="{note.channel}" data-version="{note.version}">{note.version}</a>' for note in notes)
    filters = '''<fieldset class="release-filter"><legend>Release channel</legend>
<label><input type="radio" name="channel" id="channel-all" value="all" checked> All</label>
<label><input type="radio" name="channel" id="channel-stable" value="stable"> Stable</label>
<label><input type="radio" name="channel" id="channel-nightly" value="nightly"> Nightly</label>
</fieldset>'''
    return filters + '''
<aside class="version-nav" aria-label="Release navigation">
<p class="mono vn-title">Releases</p>
<label for="release-search" hidden id="search-label">Find a release</label>
<input id="release-search" type="search" placeholder="Find a release" aria-label="Find a release" hidden>
<nav aria-label="Versions" id="versions">''' + links + '''</nav>
<a class="archive-link" href="changelog.xml">Subscribe via Atom ↗</a>
</aside>
<div class="timeline"><div id="releases">''' + '\n'.join(article(note, latest=note.version == latest) for note in notes) + '''</div>
<p id="no-releases" hidden>No matching release. <button type="button" id="clear-search">Clear filters</button></p>
<noscript><p>All release notes are available without JavaScript. Use the channel filter above to browse Stable or Nightly.</p></noscript>
'''


def detail_content(note, notes, latest):
    channel = [item for item in notes if item.channel == note.channel]
    index = channel.index(note)
    links = ['<a href="../../changelog.html">All releases</a>']
    if index + 1 < len(channel):
        older = channel[index + 1].version
        links.append(f'<a rel="prev" href="../{older}/">Previous: {older}</a>')
    if index > 0:
        newer = channel[index - 1].version
        links.append(f'<a rel="next" href="../{newer}/">Next: {newer}</a>')
    banner = '' if note.version == latest else f'<p class="latest-banner"><a href="../{latest}/">Latest is {latest}</a></p>'
    return ('<aside class="version-nav"><p class="mono vn-title">Releases</p><nav aria-label="Release navigation">' +
            '\n'.join(links) + '</nav><a class="archive-link" href="../../changelog.xml">Subscribe via Atom ↗</a></aside>\n' +
            '<div class="timeline">' + banner + article(note, '../../', note.version == latest))


def atom(notes):
    ET.register_namespace('', ATOM)
    feed = ET.Element('{' + ATOM + '}feed')
    def add(parent, name, text=None, **attributes):
        child = ET.SubElement(parent, '{' + ATOM + '}' + name, attributes)
        child.text = text
        return child
    add(feed, 'id', SITE + '/changelog')
    add(feed, 'title', 'Circa releases')
    add(feed, 'link', href=SITE + '/changelog.xml', rel='self')
    add(feed, 'link', href=SITE + '/changelog', rel='alternate')
    add(feed, 'updated', max(note.date for note in notes) + 'T00:00:00Z')
    author = add(feed, 'author')
    add(author, 'name', 'Circa')
    for note in notes:
        entry = add(feed, 'entry')
        url = SITE + '/changelog/' + note.version + '/'
        add(entry, 'id', url)
        add(entry, 'title', note.version + ' — ' + note.title)
        add(entry, 'link', href=url)
        add(entry, 'updated', note.date + 'T00:00:00Z')
        add(entry, 'published', note.date + 'T00:00:00Z')
        add(entry, 'category', term=note.channel)
        add(entry, 'summary', github_body(note))
        add(entry, 'content', article(note, SITE + '/', False), type='html')
    ET.indent(feed, space='  ')
    return ET.tostring(feed, encoding='utf-8', xml_declaration=True).decode('utf-8') + '\n'


def outputs(root=ROOT):
    notes = load_all(root)
    latest = next(note.version for note in notes if note.channel == 'stable')
    template = (root / 'scripts/templates/changelog.html').read_text(encoding='utf-8')
    files = {'web/changelog.html': page(template, index_content(notes, latest)), 'web/changelog.xml': atom(notes)}
    for note in notes:
        files[f'web/changelog/{note.version}/index.html'] = page(
            template, detail_content(note, notes, latest), 'Circa ' + note.version,
            SITE + '/changelog/' + note.version + '/', '../../')
    return files


def generate(root=ROOT, check=False):
    files = outputs(root)
    stale = []
    expected = {root / path for path in files}
    # Only remove obsolete generated pages; never touch manually authored files.
    obsolete = [path for path in (root / 'web/changelog').glob('*/index.html')
                if path not in expected and GENERATED in path.read_text(encoding='utf-8')]
    for name, content in files.items():
        path = root / name
        if not path.is_file() or path.read_bytes() != content.encode('utf-8'):
            stale.append(name)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(content.encode('utf-8'))
    if check:
        if stale or obsolete:
            raise ValueError('Changelog is out of date; run python3 scripts/changelog.py build:\n' +
                             '\n'.join(stale + [str(path.relative_to(root)) for path in obsolete]))
    else:
        for path in obsolete:
            path.unlink()
            if not any(path.parent.iterdir()):
                path.parent.rmdir()
    return len(files)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['build', 'check'])
    args = parser.parse_args()
    try:
        count = generate(check=args.command == 'check')
    except (ValueError, OSError) as error:
        parser.exit(1, str(error) + '\n')
    print(f'Changelog {args.command}: {count} files')


if __name__ == '__main__':
    main()
